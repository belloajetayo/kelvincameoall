  <script>
  function switchContactMode(mode) {
    const tabInquiry = document.getElementById('tabBtnInquiry');
    const tabCareers = document.getElementById('tabBtnCareers');
    const viewInquiry = document.getElementById('viewInquiry');
    const viewCareers = document.getElementById('viewCareers');

    if (mode === 'careers') {
      tabCareers.style.background = 'var(--navy-900)';
      tabCareers.style.color = 'var(--white)';
      tabInquiry.style.background = 'transparent';
      tabInquiry.style.color = 'var(--slate-700)';
      viewInquiry.style.display = 'none';
      viewCareers.style.display = 'block';
    } else {
      tabInquiry.style.background = 'var(--navy-900)';
      tabInquiry.style.color = 'var(--white)';
      tabCareers.style.background = 'transparent';
      tabCareers.style.color = 'var(--slate-700)';
      viewInquiry.style.display = 'block';
      viewCareers.style.display = 'none';
    }
  }

  function prefillJobRole(roleName) {
    switchContactMode('careers');
    const select = document.getElementById('jobPositionSelect');
    if (select) {
      select.value = roleName;
    }
    const panel = document.getElementById('contactFormPanel');
    if (panel) {
      panel.scrollIntoView({ behavior: 'smooth' });
    }
  }

